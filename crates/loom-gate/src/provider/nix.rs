type Nodes = BTreeMap<StorePath, std::sync::Arc<Node>>;

fn read_graph(tool: &Path, root: &StorePath) -> Result<Nodes, Error> {
    read_graphs(tool, std::slice::from_ref(root))
}

fn read_graphs(tool: &Path, roots: &[StorePath]) -> Result<Nodes, Error> {
    let mut arguments = vec!["derivation", "show", "--recursive"];
    arguments.extend(roots.iter().map(StorePath::as_str));
    let document: Document = serde_json::from_slice(&query(tool, &arguments)?)?;
    if document.version != 4 {
        return Err(Error::Version);
    }
    document
        .derivations
        .into_iter()
        .map(|(path, raw)| {
            if raw.version != 4 {
                return Err(Error::Version);
            }
            let mut outputs = BTreeMap::new();
            let fixed = raw.outputs.values().any(|output| output.hash.is_some());
            for (name, output) in raw.outputs {
                let path = match output.path {
                    Some(path) => StorePath::basename(&path)?,
                    None if output.hash.is_some() && output.method.is_some() => raw
                        .env
                        .get(name.as_str())
                        .ok_or(Error::Output)?
                        .clone()
                        .try_into()?,
                    None => return Err(Error::Output),
                };
                outputs.insert(name, path);
            }
            let dependencies = raw
                .inputs
                .drvs
                .into_iter()
                .map(|(path, dependency)| {
                    if !dependency.dynamic.is_empty() || dependency.outputs.is_empty() {
                        return Err(Error::Dynamic);
                    }
                    Ok((StorePath::basename(&path)?, dependency.outputs))
                })
                .collect::<Result<_, Error>>()?;
            let sources = raw
                .inputs
                .srcs
                .into_iter()
                .map(|path| StorePath::basename(&path))
                .collect::<Result<_, _>>()?;
            Ok((
                StorePath::basename(&path)?,
                std::sync::Arc::new(Node {
                    builder: raw.builder,
                    system: raw.system,
                    args: raw.args,
                    env: raw.env,
                    structured: raw.structured,
                    fixed,
                    sources,
                    dependencies,
                    outputs,
                }),
            ))
        })
        .collect()
}

fn read_resources(
    tool: &Path,
    nodes: &Nodes,
    evaluation: &BTreeSet<StorePath>,
) -> Result<BTreeMap<StorePath, Resource>, Error> {
    let mut sources: BTreeSet<_> = nodes
        .values()
        .flat_map(|node| node.sources.iter().cloned())
        .collect();
    sources.insert(StorePath::root(tool)?);
    sources.extend(evaluation.iter().cloned());
    let mut arguments = vec![
        "path-info",
        "--recursive",
        "--json",
        "--json-format",
        "1",
        "--offline",
    ];
    arguments.extend(sources.iter().map(StorePath::as_str));
    let paths: BTreeMap<StorePath, Option<Resource>> =
        serde_json::from_slice(&query(tool, &arguments)?)?;
    for source in &sources {
        if !paths.get(source).is_some_and(Option::is_some) {
            return Err(Error::Resource {
                path: source.clone(),
            });
        }
    }
    let resources: BTreeMap<_, _> = paths
        .into_iter()
        .map(|(path, resource)| {
            let resource = resource.ok_or_else(|| Error::Resource { path: path.clone() })?;
            Ok((path, resource))
        })
        .collect::<Result<_, Error>>()?;
    for resource in resources.values() {
        for reference in &resource.references {
            if !resources.contains_key(reference) {
                return Err(Error::Resource {
                    path: reference.clone(),
                });
            }
        }
    }
    Ok(resources)
}

fn check_execution_graph(nodes: &Nodes, root: &StorePath) -> Result<(), Error> {
    let check = nodes.get(root).ok_or(Error::Root)?;
    if check.fixed {
        return Err(Error::FixedCheck);
    }
    let mut pending = vec![root.clone()];
    let mut executable = BTreeSet::new();
    while let Some(path) = pending.pop() {
        if !executable.insert(path.clone()) {
            continue;
        }
        let node = nodes.get(&path).ok_or(Error::Root)?;
        pending.extend(node.dependencies.keys().cloned());
    }
    // Derivation documents in source edges are pinned readonly data. Their
    // instructions are not execution permissions or realization dependencies.
    for path in &executable {
        let node = nodes.get(path).ok_or(Error::Root)?;
        if node.outputs.is_empty() {
            return Err(Error::Output);
        }
        let mut inputs = node.sources.clone();
        for (dependency, outputs) in &node.dependencies {
            let input = nodes.get(dependency).ok_or_else(|| Error::Dependency {
                derivation: dependency.clone(),
            })?;
            for output in outputs {
                inputs.insert(input.outputs.get(output).ok_or(Error::Output)?.clone());
            }
        }
        // Fixed prerequisites are content-pinned inputs; the frontier never realizes them.
        if node.fixed {
            continue;
        }
        if [
            "__noChroot",
            "__impure",
            "__darwinAllowLocalNetworking",
            "__darwinImpureHostDeps",
        ]
        .iter()
        .any(|key| requests(node, key))
        {
            return Err(Error::Unsafe {
                derivation: path.clone(),
            });
        }
        let builder = StorePath::root(Path::new(&node.builder))?;
        if !inputs.contains(&builder) {
            return Err(Error::Builder {
                derivation: path.clone(),
            });
        }
    }
    Ok(())
}

fn requests(node: &Node, key: &str) -> bool {
    node.env
        .get(key)
        .is_some_and(|value| !value.is_empty() && value != "0")
        || node
            .structured
            .as_ref()
            .and_then(|attributes| attributes.get(key))
            .is_some_and(|value| match value {
                serde_json::Value::Null => false,
                serde_json::Value::Bool(value) => *value,
                serde_json::Value::Number(value) => value.as_i64() != Some(0),
                serde_json::Value::String(value) => !value.is_empty() && value != "0",
                serde_json::Value::Array(value) => !value.is_empty(),
                serde_json::Value::Object(value) => !value.is_empty(),
            })
}

fn locate_tool() -> Result<PathBuf, Error> {
    let search = std::env::var_os("PATH").ok_or(Error::Capability)?;
    for directory in std::env::split_paths(&search) {
        let candidate = directory.join("nix");
        if candidate.is_file() {
            let canonical = candidate.canonicalize()?;
            StorePath::root(&canonical)?;
            return Ok(canonical);
        }
    }
    Err(Error::Capability)
}

// The checked adapter owns its modern CLI requirements rather than inheriting
// ambient NIX_CONFIG (which is deliberately removed at this boundary).
fn native_command(tool: &Path, args: &[&str]) -> Command {
    let mut command = Command::new(tool);
    command
        .args(args)
        .env_remove("NIX_CONFIG")
        .env_remove("NIX_PATH")
        .args([
            "--extra-experimental-features",
            "nix-command flakes",
            "--option",
            "accept-flake-config",
            "false",
        ]);
    loom_driver::workspace::cargo::discovery_command(&mut command);
    command
}

#[cfg(test)]
mod command_tests;

fn invoke(tool: &Path, args: &[&str]) -> Result<Output, Error> {
    let clock = loom_driver::clock::SystemClock::new();
    let started = loom_driver::clock::Clock::now(&clock);
    tracing::debug!(
        operation = args.first().copied(),
        "native Nix operation started"
    );
    let output = native_command(tool, args).output()?;
    tracing::debug!(operation = args.first().copied(), elapsed = ?loom_driver::clock::Clock::now(&clock).saturating_duration_since(started), code = output.status.code(), stdout_bytes = output.stdout.len(), "native Nix operation finished");
    Ok(output)
}

fn query(tool: &Path, args: &[&str]) -> Result<Vec<u8>, Error> {
    let output = invoke(tool, args)?;
    if !output.status.success() {
        return Err(Error::Query {
            detail: diagnostic(&output.stderr),
        });
    }
    Ok(output.stdout)
}

fn diagnostic(bytes: &[u8]) -> String {
    crate::inputs::bounded_query_tail_diagnostic(&String::from_utf8_lossy(bytes)).replace(
        "use '--no-sandbox' to disable sandboxing",
        "provision the declared sandbox capability and retry `loom gate verify`",
    )
}

#[derive(Debug, Display, Error)]
pub enum Error {
    /// isolated delegated-native execution failed
    Managed(#[from] managed::Error),
    /// native {kind:?} {flake:?}#{system:?}.{attribute:?} has an invalid execution or source partition
    Binding {
        flake: ResourcePath,
        kind: crate::inventory::nix::Kind,
        system: Name,
        attribute: Name,
        #[source]
        source: Box<Error>,
    },
    /// native app definition is not the fixed immutable program-artifact check; use the app constructor without execution overrides
    AppDefinition,
    /// Cargo responsibility disagrees with the actual native execution; use the fixed Cargo constructor without phase overrides and retry `loom gate verify`
    CargoExecution,
    /// invalid supervised native report: {detail}
    Report { detail: String },
    /// supervised native producer exited {code}: {detail}
    ReportInfrastructure { code: i32, detail: String },
    /// native Rust catalogue is invalid: {detail}; rebuild the actual Cargo/Nextest preparation and retry `loom gate verify`
    Catalogue { detail: String },
    /// no compiled native test matches `{target:?}`; correct the exact native identity and retry `loom gate verify`
    MissingCase { target: Name },
    /// ambiguous compiled native test `{target:?}`; use its binary-qualified identity and retry `loom gate verify`
    AmbiguousCase { target: Name },
    /// native compiler preparation did not verify: {observed:?}; provision its declared capability or correct its source and retry `loom gate verify`
    Preparation { observed: Box<Observed> },
    /// invalid NAR identity; native resources must have canonical SHA256 content hashes
    NarHash,
    /// native resource closure omitted `{path:?}`; provision the declared store inputs and retry `loom gate verify`
    Resource { path: StorePath },
    /// invalid Nix store identity; use a native immutable store resource, not a host path
    StorePath,
    /// subject `{subject:?}` is outside the staged native project; construct its actual resource before offering responsibility and retry `loom gate verify`
    Outside { subject: Name },
    /// native Nix subject `{subject:?}` is not a discovered derivation; correct the project target and retry `loom gate verify`
    Native { subject: Name },
    /// native app `{subject:?}` is a host program, not a hermetic execution; bind a checked derivation or its specifically supported effect and retry `loom gate verify`
    App { subject: Name },
    /// native source omits `{path:?}` required by subject `{subject:?}`; construct its actual resource and retry `loom gate verify`
    Omitted { subject: Name, path: ResourcePath },
    /// native check has no supported checked source definition; use nix/verification.nix resource/check constructors and retry `loom gate verify`
    Sources,
    /// native source `{path:?}` disagrees with its captured repository origin; correct the resource constructor and retry `loom gate verify`
    Origin { path: ResourcePath },
    /// native graph captures the entire evaluation project; construct independent source resources instead of src = self and retry `loom gate verify`
    WholeSource,
    /// native graph changes in its isolated source partition; include the actual evaluator/resource inputs and retry `loom gate verify`
    Partition,
    /// Nix discovery capability is unavailable; provision Nix and retry `loom gate verify`
    Capability,
    /// Nix resource I/O failed
    Io(#[from] std::io::Error),
    /// captured Nix project changed
    Snapshot(#[from] crate::inventory::snapshot::Error),
    /// malformed native derivation graph; investigate the producer with `nix derivation show --recursive` and retry `loom gate verify`
    Json(#[from] serde_json::Error),
    /// native Nix query failed: {detail}; correct the definition or provision its declared inputs and retry `loom gate verify`
    Query { detail: String },
    /// native check system `{expected:?}` disagrees with derivation system `{actual:?}`; correct the output binding and retry `loom gate verify`
    System { expected: Name, actual: Name },
    /// pinned input `{derivation:?}` is cold; route its declared acquisition through trusted-driver input provisioning before retrying offline verification
    ColdInput { derivation: StorePath },
    /// native Nix query was not UTF-8
    Encoding,
    /// unsupported derivation graph version; provision Nix with graph format 4 and retry `loom gate verify`
    Version,
    /// derivation graph omitted its requested root
    Root,
    /// derivation graph omits captured project source `{source_path:?}`; stage the checked project in the native check and retry `loom gate verify`
    Source { source_path: StorePath },
    /// a deterministic check cannot be a network-enabled fixed-output derivation; construct a sandboxed check over pinned resources and retry `loom gate verify`
    FixedCheck,
    /// derivation graph has unresolved outputs; supply fixed native output mappings and retry `loom gate verify`
    Output,
    /// dynamic derivation dependencies are unsupported; use a statically constructed graph and retry `loom gate verify`
    Dynamic,
    /// native graph changed: {detail}; reconstruct its actual inputs and retry `loom gate verify`
    GraphDrift { detail: String },
    /// derivation `{derivation:?}` requests impure or unsandboxed execution; correct the deterministic definition and retry `loom gate verify`
    Unsafe { derivation: StorePath },
    /// graph omitted transitive derivation `{derivation:?}`; repair native construction and retry `loom gate verify`
    Dependency { derivation: StorePath },
    /// derivation `{derivation:?}` builder is outside its constructed inputs; pin the actual tool resource and retry `loom gate verify`
    Builder { derivation: StorePath },
    /// Nix tool changed after construction; regenerate the checked definition and retry `loom gate verify`
    ToolChanged,
    /// Nix graph changed after construction; regenerate the checked definition and retry `loom gate verify`
    GraphChanged,
    /// Nix returned inconsistent derivation/output results; investigate the executor and retry `loom gate verify`
    Result,
}
