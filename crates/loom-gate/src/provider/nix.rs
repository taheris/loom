/// One immutable Nix store object, never an arbitrary host path or installable expression.
#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord, Serialize, Deserialize)]
#[serde(try_from = "String")]
pub struct StorePath(String);

impl TryFrom<String> for StorePath {
    type Error = Error;

    fn try_from(value: String) -> Result<Self, Error> {
        let base = value.strip_prefix("/nix/store/").ok_or(Error::StorePath)?;
        if base.len() < 34
            || !base.as_bytes()[..32]
                .iter()
                .all(|byte| b"0123456789abcdfghijklmnpqrsvwxyz".contains(byte))
            || base.as_bytes()[32] != b'-'
            || !base[33..]
                .bytes()
                .all(|byte| byte.is_ascii_alphanumeric() || b"+-._=?".contains(&byte))
        {
            return Err(Error::StorePath);
        }
        Ok(Self(value))
    }
}

impl StorePath {
    pub fn as_str(&self) -> &str {
        &self.0
    }

    fn basename(value: &str) -> Result<Self, Error> {
        Self::try_from(format!("/nix/store/{value}"))
    }

    fn root(path: &Path) -> Result<Self, Error> {
        if !path.is_absolute()
            || path
                .components()
                .skip(1)
                .any(|part| !matches!(part, Component::Normal(_)))
        {
            return Err(Error::StorePath);
        }
        let root: PathBuf = path.components().take(4).collect();
        Self::try_from(root.to_str().ok_or(Error::StorePath)?.to_owned())
    }
}

/// A fixed Cargo operation generated by the native constructor, not caller command wiring.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "kebab-case")]
pub(crate) enum CargoOperation {
    Build,
    Lint,
    LintAllTargets,
    Test,
    Catalogue,
}

impl CargoOperation {
    const fn command(self) -> &'static str {
        match self {
            Self::Build => {
                "cargo build --offline --locked --manifest-path \"$src/Cargo.toml\" --workspace --all-targets --profile \"$CARGO_PROFILE\""
            }
            Self::Lint => {
                "cargo clippy --offline --locked --workspace --profile \"$CARGO_PROFILE\" -- --deny warnings"
            }
            Self::LintAllTargets => {
                "cargo clippy --offline --locked --workspace --all-targets --profile \"$CARGO_PROFILE\" -- --deny warnings"
            }
            Self::Test => {
                concat!(
                    "runtime=$(mktemp -d)\n",
                    "cp -R \"${LOOM_TEST_SOURCE_ROOT:-$src}/.\" \"$runtime\"\n",
                    "chmod -R u+w \"$runtime\"\n",
                    "export LOOM_TEST_SOURCE_ROOT=\"$runtime\"\n",
                    "cd \"$runtime\"\n",
                    "git init -q\n",
                    "git add --all\n",
                    "git -c user.name='Loom native suite' -c user.email='native@example.invalid' -c commit.gpgsign=false commit -q -m 'Capture native suite source'\n",
                    "bash \"$LOOM_PRIVATE_FIXTURE_RUNNER\" --build-campaign bash \"$LOOM_REPORT_SUPERVISOR\" cargo nextest run --cargo-metadata \"$cargoArtifacts/cargo.json\" --binaries-metadata \"$cargoArtifacts/binaries.json\" --workspace-remap \"$runtime\" --target-dir-remap \"$cargoArtifacts/target\" --ignore-default-filter --no-fail-fast --message-format libtest-json-plus\n",
                )
            }
            Self::Catalogue => concat!(
                "mkdir -p \"$out\"\n",
                "cargo metadata --offline --locked --manifest-path \"$src/Cargo.toml\" --format-version 1 > \"$out/cargo.json\"\n",
                "cargo nextest list --offline --locked --manifest-path \"$src/Cargo.toml\" --workspace --all-targets --cargo-profile \"$CARGO_PROFILE\" --run-ignored all --ignore-default-filter --list-type binaries-only --message-format json > \"$out/binaries.json\"\n",
                "listing_platform=$(jq -ce '.\"rust-build-meta\".platforms | if (.targets | length) == 0 then .host.platform elif (.targets | length) == 1 then .targets[0].platform else error(\"unsupported catalogue targets\") end | select((.triple | type) == \"string\" and (.triple | length) > 0)' \"$out/binaries.json\")\n",
                "listing_target=$(jq -er '.triple' <<< \"$listing_platform\")\n",
                "if jq -e 'has(\"custom-json\")' <<< \"$listing_platform\" > /dev/null; then\n",
                "  jq -er '.\"custom-json\"' <<< \"$listing_platform\" > \"$out/listing-target.json\"\n",
                "  listing_target=\"$out/listing-target.json\"\n",
                "fi\n",
                "listing_build_directory=$(jq -er '.\"rust-build-meta\" | (.\"build-directory\" // .\"target-directory\") | select(type == \"string\" and length > 0)' \"$out/binaries.json\")\n",
                "cargo metadata --offline --locked --manifest-path \"$src/Cargo.toml\" --format-version 1 --all-features --filter-platform \"$listing_target\" > \"$out/listing-cargo.json\"\n",
                "cargo nextest list --cargo-metadata \"$out/listing-cargo.json\" --binaries-metadata \"$out/binaries.json\" --workspace-remap \"$src\" --target-dir-remap \"$out/target\" --build-dir-remap \"$listing_build_directory\" --run-ignored all --ignore-default-filter --message-format json > \"$out/nextest.json\"\n",
                "cargo nextest list --cargo-metadata \"$out/listing-cargo.json\" --binaries-metadata \"$out/binaries.json\" --workspace-remap \"$src\" --target-dir-remap \"$out/target\" --build-dir-remap \"$listing_build_directory\" --run-ignored all --message-format json > \"$out/default.json\"\n",
                "printf '%s' \"$LOOM_NATIVE_GROUPS\" > \"$out/groups.txt\"\n",
                "index=0\n",
                "while IFS= read -r group; do\n",
                "  cargo nextest list --cargo-metadata \"$out/listing-cargo.json\" --binaries-metadata \"$out/binaries.json\" --workspace-remap \"$src\" --target-dir-remap \"$out/target\" --build-dir-remap \"$listing_build_directory\" --run-ignored all --ignore-default-filter -E \"group(=$group)\" --message-format json > \"$out/group-$index.json\"\n",
                "  index=$((index + 1))\n",
                "done <<< \"$LOOM_NATIVE_GROUPS\"\n",
            ),
        }
    }

    const fn duty(self) -> Option<Duty> {
        match self {
            Self::Build => Some(Duty::Build),
            Self::Lint | Self::LintAllTargets => Some(Duty::Lint),
            Self::Test => Some(Duty::Test),
            Self::Catalogue => None,
        }
    }

    fn require_execution(self, root: &Node) -> Result<(), Error> {
        let target = if self == Self::Catalogue {
            "$out"
        } else {
            "$PWD"
        };
        let expected = format!(
            "runHook preBuild\ncargo --version\nexport HOME=$(mktemp -d)\nexport GIT_CONFIG_SYSTEM=/dev/null\nexport CARGO_TARGET_DIR=\"{target}/target\"\n{}\n\nrunHook postBuild\n",
            self.command()
        );
        require_cargo_builder(root)?;
        if self == Self::Test {
            for (name, expected) in [
                (
                    "LOOM_PRIVATE_FIXTURE_RUNNER",
                    include_str!("../../../../nix/private-fixture-tests.sh"),
                ),
                (
                    "LOOM_FIXTURE_INPUT_LOADER",
                    include_str!("../../../../nix/retain-fixture-inputs.sh"),
                ),
                (
                    "LOOM_TEST_SCHEDULING",
                    include_str!("../../../../nix/test-scheduling.sh"),
                ),
            ] {
                let path = root.env.get(name).ok_or(Error::CargoExecution)?;
                StorePath::root(Path::new(path))?;
                if std::fs::read_to_string(path)? != expected {
                    return Err(Error::CargoExecution);
                }
            }
            report::require_supervisor(
                root.env
                    .get("LOOM_REPORT_SUPERVISOR")
                    .ok_or(Error::CargoExecution)?,
            )?;
            if root
                .env
                .get("NEXTEST_EXPERIMENTAL_LIBTEST_JSON")
                .map(String::as_str)
                != Some("1")
            {
                return Err(Error::CargoExecution);
            }
        }
        if root.env.get("buildPhase") != Some(&expected)
            || [
                "preBuild",
                "postBuild",
                "phases",
                "dontBuild",
                "buildCommand",
                "buildCommandPath",
                "BASH_ENV",
                "ENV",
                "NEXTEST_PROFILE",
                "NEXTEST_USER_CONFIG_FILE",
            ]
            .iter()
            .any(|key| root.env.get(*key).is_some_and(|value| !value.is_empty()))
        {
            return Err(Error::CargoExecution);
        }
        Ok(())
    }
}

fn require_catalogue(definition: &Native, nodes: &Nodes) -> Result<(), Error> {
    let Some(catalogue) = &definition.catalogue else {
        return if definition.cargo == Some(CargoOperation::Test) {
            Err(Error::CargoExecution)
        } else {
            Ok(())
        };
    };
    if definition.cargo != Some(CargoOperation::Test) {
        return Err(Error::CargoExecution);
    }
    let root = nodes.get(&definition.root).ok_or(Error::Root)?;
    let prepared = nodes.get(catalogue).ok_or(Error::CargoExecution)?;
    CargoOperation::Catalogue.require_execution(prepared)?;
    let (out, output) = prepared
        .outputs
        .iter()
        .find(|(name, _)| name.as_str() == "out")
        .ok_or(Error::CargoExecution)?;
    if root.env.get("cargoArtifacts").map(String::as_str) != Some(output.as_str())
        || root
            .dependencies
            .get(catalogue)
            .is_none_or(|outputs| !outputs.contains(out))
    {
        return Err(Error::CargoExecution);
    }
    require_compilation_inputs(root, prepared)
}

fn require_compilation_inputs(root: &Node, prepared: &Node) -> Result<(), Error> {
    if [
        "src",
        "nativeBuildInputs",
        "buildInputs",
        "cargoVendorDir",
        "CARGO_PROFILE",
    ]
    .iter()
    .any(|key| root.env.get(*key) != prepared.env.get(*key))
    {
        return Err(Error::CargoExecution);
    }
    Ok(())
}

fn require_cargo_builder(root: &Node) -> Result<(), Error> {
    let [flag, setup, build] = root.args.as_slice() else {
        return Err(Error::CargoExecution);
    };
    if flag != "-e"
        || Path::new(&root.builder)
            .file_name()
            .is_none_or(|name| name != "bash")
    {
        return Err(Error::CargoExecution);
    }
    let setup = StorePath::try_from(setup.clone())?;
    let build = StorePath::try_from(build.clone())?;
    let source = "if [ -e \"$NIX_ATTRS_SH_FILE\" ]; then . \"$NIX_ATTRS_SH_FILE\"; fi\nsource \"$stdenv/setup\"\nsource \"$1\"\n";
    if std::fs::read_to_string(setup.as_str())? != source
        || std::fs::read_to_string(build.as_str())? != "genericBuild\n"
    {
        return Err(Error::CargoExecution);
    }
    Ok(())
}

#[derive(Clone, Copy)]
enum Offering<'a> {
    Explicit {
        subjects: &'a BTreeSet<Name>,
        duties: &'a BTreeSet<Duty>,
    },
    Baseline,
}

impl Definition {
    /// Project constructor-declared opaque results without changing the independent baseline.
    ///
    /// # Errors
    /// Rejects a result identity that cannot be bound to the captured definition.
    pub fn reported_cases(&self) -> Result<Vec<Self>, super::Error> {
        let Execution::Nix(graph) = &self.execution else {
            return Ok(Vec::new());
        };
        let Some(contract) = &graph.report else {
            return Ok(Vec::new());
        };
        contract
            .targets
            .iter()
            .map(|target| {
                let mut definition = self.clone().named(target.clone())?;
                definition.execution = Execution::Report {
                    graph: graph.clone(),
                    target: target.clone(),
                };
                Ok(definition)
            })
            .collect()
    }

    /// Construct conservative Nix evaluation/check duties from actual captured sources.
    ///
    /// Rust duties require the fixed Cargo constructor; other outputs and document assertions are not inferred.
    ///
    /// # Errors
    /// Rejects missing native bindings, incomplete sources and unsafe execution graphs.
    pub fn hermetic_baseline(
        snapshot: &Snapshot,
        inventory: &Inventory,
        target: Name,
        native: &Name,
    ) -> Result<Self, super::Error> {
        Self::construct_native(snapshot, inventory, target, native, Offering::Baseline)
    }

    /// Bind native baselines together, revalidating their complete graphs in one read.
    /// This shares no execution outcomes or validation across calls.
    ///
    /// # Errors
    /// Rejects the entire batch on stale context or an invalid native binding.
    pub fn hermetic_baselines(
        snapshot: &Snapshot,
        inventory: &Inventory,
        targets: &[(Name, Name)],
    ) -> Result<Vec<Self>, super::Error> {
        super::require_context(snapshot, inventory)?;
        let mut definitions = Vec::<Self>::new();
        for (target, native) in targets {
            if inventory.subject(native)?.nix_target().is_none() {
                return Err(Error::Native {
                    subject: native.clone(),
                }
                .into());
            }
            // One platform operation already accounts for its sibling exports.
            // Preserve explicit aliases without rediscovering the same operation.
            let definition = if let Some(previous) = definitions
                .iter()
                .find(|definition| definition.native_applicability_covers(native))
            {
                previous.clone().named(target.clone())?
            } else {
                Self::bind_native(
                    snapshot,
                    inventory,
                    target.clone(),
                    native,
                    Offering::Baseline,
                )?
            };
            definitions.push(definition);
        }
        let mut current = super::Current::new(&definitions)?;
        for definition in &definitions {
            current.require(definition)?;
        }
        super::require_context(snapshot, inventory)?;
        Ok(definitions)
    }

    /// Construct from one discovered native check; the captured project is the staged source.
    ///
    /// # Errors
    /// Rejects absent native targets, missing responsibility, omitted source and unsafe graphs.
    pub fn hermetic(
        snapshot: &Snapshot,
        inventory: &Inventory,
        target: Name,
        native: &Name,
        subjects: &BTreeSet<Name>,
        duties: &BTreeSet<Duty>,
    ) -> Result<Self, super::Error> {
        Self::construct_native(
            snapshot,
            inventory,
            target,
            native,
            Offering::Explicit { subjects, duties },
        )
    }

    fn construct_native(
        snapshot: &Snapshot,
        inventory: &Inventory,
        target: Name,
        native: &Name,
        offering: Offering<'_>,
    ) -> Result<Self, super::Error> {
        super::require_context(snapshot, inventory)?;
        let definition = Self::bind_native(snapshot, inventory, target.clone(), native, offering)?;
        definition
            .require_current()
            .map_err(|source| super::Error::Construction {
                target,
                producer: definition.description().origin().clone(),
                source: Box::new(source),
            })?;
        super::require_context(snapshot, inventory)?;
        Ok(definition)
    }

    fn bind_native(
        snapshot: &Snapshot,
        inventory: &Inventory,
        target: Name,
        native: &Name,
        offering: Offering<'_>,
    ) -> Result<Self, super::Error> {
        let subject = inventory.subject(native)?;
        let binding = subject.nix_target().ok_or_else(|| Error::Native {
            subject: native.clone(),
        })?;
        if binding.kind() == crate::inventory::nix::Kind::App
            && !matches!(offering, Offering::Baseline)
        {
            return Err(Error::App {
                subject: native.clone(),
            }
            .into());
        }
        if matches!(offering, Offering::Explicit { .. })
            && inventory.platform() == crate::scope::Platform::Native
            && binding.usage() == crate::inventory::nix::Usage::Inapplicable
        {
            return Err(Error::PlatformScope {
                subject: native.clone(),
            }
            .into());
        }
        if matches!(offering, Offering::Baseline)
            && binding.usage() == crate::inventory::nix::Usage::Inapplicable
            && let Some(definition) =
                Self::native_inapplicable(snapshot, inventory, target.clone(), native)?
        {
            return Ok(definition);
        }
        // Bind immutable discovery facts here. The public constructors revalidate
        // source, graph, tools and resources before returning any definitions.
        let graph = if let Some(graph) = inventory.native_graph(native) {
            if graph.tool != locate_tool()? {
                return Err(Error::GraphChanged.into());
            }
            graph.clone()
        } else {
            Arc::new(
                Graph::construct(snapshot, inventory, binding).map_err(|source| {
                    super::Error::Construction {
                        target: target.clone(),
                        producer: binding.flake().clone(),
                        source: Box::new(source.into()),
                    }
                })?,
            )
        };
        let (subjects, responsibilities) = match offering {
            Offering::Explicit { subjects, duties } => (
                subjects.clone(),
                super::responsibility(inventory, &target, subjects, duties)?,
            ),
            Offering::Baseline => baseline(inventory, native, &graph),
        };
        for responsibility in &responsibilities {
            if inventory.subject(responsibility.responsible())?.role()
                == crate::inventory::Role::RustSource
                && graph.cargo.and_then(CargoOperation::duty) != Some(responsibility.duty())
            {
                return Err(Error::CargoExecution.into());
            }
        }
        let mut inputs = BTreeMap::<ResourcePath, BTreeSet<Origin>>::new();
        let directory = binding.flake().as_path().parent().ok_or(Error::StorePath)?;
        for name in &subjects {
            let subject = inventory.subject(name)?;
            if subject
                .members()
                .iter()
                .any(|path| !path.as_path().starts_with(directory))
            {
                return Err(Error::Outside {
                    subject: name.clone(),
                }
                .into());
            }
        }
        for path in &graph.inputs {
            inputs
                .entry(path.clone())
                .or_default()
                .insert(Origin::Definition(binding.flake().clone()));
        }
        for name in &subjects {
            let subject = inventory.subject(name)?;
            for path in subject.members() {
                if !(graph.origins.contains(path)
                    || (matches!(
                        subject.role(),
                        crate::inventory::Role::NixSource | crate::inventory::Role::Configuration
                    ) && graph.evaluation_origins.contains(path))
                    || subject.nix_target().is_some() && graph.inputs.contains(path))
                {
                    return Err(Error::Omitted {
                        subject: name.clone(),
                        path: path.clone(),
                    }
                    .into());
                }
                inputs
                    .entry(path.clone())
                    .or_default()
                    .insert(Origin::Subject(name.clone()));
            }
        }
        let inputs = super::capture_inputs(snapshot, inputs)?;
        let executor = StorePath::root(&graph.tool)?;
        let binary = ResourcePath::try_from(
            graph
                .tool
                .strip_prefix(executor.as_str())
                .map_err(|_| Error::StorePath)?
                .to_path_buf(),
        )?;
        let execution = wire::Nix {
            flake: binding.flake().clone(),
            attribute: binding.attribute().clone(),
            system: binding.system().clone(),
            graph: graph.identity.clone(),
            derivation: graph.root.clone(),
            source: graph.source.clone(),
            executor,
            binary,
            artifact: graph.artifact.clone(),
            runtime: graph.runtime,
            purpose: graph.purpose,
            process: graph.process.clone(),
        };
        let definition = Digest::of(&serde_json::to_vec(&(
            snapshot.identity(),
            &target,
            &responsibilities,
            &inputs,
            &execution,
        ))?);
        let contract = wire::Contract {
            target,
            snapshot: snapshot.identity().clone(),
            definition,
            origin: binding.flake().clone(),
            responsibilities,
            inputs,
        };
        let candidate = if matches!(graph.runtime, Runtime::NativeProcess | Runtime::NativeStore) {
            Candidate::NativeProcess {
                contract,
                execution,
            }
        } else {
            Candidate::HermeticNix {
                contract,
                execution,
            }
        };
        Ok(Self {
            platform: inventory.platform(),
            candidate,
            execution: Execution::Nix(graph),
        })
    }
}

fn baseline(
    inventory: &Inventory,
    native: &Name,
    graph: &Graph,
) -> (BTreeSet<Name>, BTreeSet<super::Responsibility>) {
    use crate::inventory::Role;
    let subjects: BTreeSet<_> = inventory
        .subjects()
        .values()
        .filter(|subject| {
            subject.name() == native
                || (subject.nix_target().is_none()
                    && (matches!(
                        subject.role(),
                        Role::NixSource
                            | Role::Configuration
                            | Role::RuntimeResource
                            | Role::TestFixture
                    ) || (subject.role() == Role::RustSource
                        && graph.cargo.is_some_and(|operation| {
                            operation != CargoOperation::Lint
                                || inventory.is_production(subject.name())
                        })))
                    && !subject.members().is_empty()
                    && subject.members().iter().all(|path| {
                        graph.origins.contains(path)
                            || (matches!(subject.role(), Role::NixSource | Role::Configuration)
                                && graph.evaluation_origins.contains(path))
                    }))
        })
        .map(|subject| subject.name().clone())
        .collect();
    let responsibilities = inventory
        .obligations()
        .iter()
        .filter(|obligation| {
            subjects.contains(obligation.subject())
                && subjects.contains(obligation.responsible())
                && (matches!(obligation.duty(), Duty::Evaluate | Duty::Check)
                    || graph.cargo.is_some_and(|operation| {
                        inventory.subjects()[obligation.responsible()].role() == Role::RustSource
                            && operation.duty() == Some(obligation.duty())
                    }))
        })
        .map(super::Responsibility::from_obligation)
        .collect();
    (subjects, responsibilities)
}

/// A graph is constructed by evaluating the captured native definition, not deserialized by callers.
#[derive(Debug)]
pub struct Graph {
    // Availability ownership, not verification evidence or a freshness cache.
    _retained: Vec<std::sync::Arc<pin::Inputs>>,
    tool: PathBuf,
    artifact: Digest,
    root: StorePath,
    source: StorePath,
    inputs: BTreeSet<ResourcePath>,
    origins: BTreeSet<ResourcePath>,
    explicit_file_origins: BTreeSet<ResourcePath>,
    evaluation_origins: BTreeSet<ResourcePath>,
    recipes: recipe::Captured,
    nodes: Nodes,
    execution: frontier::Execution,
    provenance: Vec<Source>,
    resources: BTreeMap<StorePath, Resource>,
    identity: Digest,
    evaluation: BTreeSet<StorePath>,
    cargo: Option<CargoOperation>,
    catalogue: Option<StorePath>,
    report: Option<report::Contract>,
    reporter: Option<StorePath>,
    runtime: Runtime,
    purpose: Purpose,
    managed: Option<managed::Executor>,
    process: Option<process::Context>,
}

